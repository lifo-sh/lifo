import { describe, expect, it } from 'vitest';
import { isPublicAddress } from '../src/address';

describe('isPublicAddress', () => {
  it.each([
    '0.0.0.0', '10.1.2.3', '100.64.0.1', '100.127.255.255', '127.0.0.1', '127.255.255.254', '169.254.169.254',
    '172.16.0.1', '172.31.255.255', '192.0.0.8', '192.0.2.5', '192.168.1.1', '198.18.0.1', '198.51.100.7',
    '203.0.113.9', '224.0.0.1', '239.255.255.250', '240.0.0.1', '255.255.255.255',
    '::', '::1', '[::1]', 'fc00::1', 'fd12:3456::1', 'fe80::1', 'fe80::1%en0', 'fec0::1', 'ff02::1', '2001:db8::1',
    '::ffff:127.0.0.1', '::ffff:7f00:1', '::ffff:169.254.169.254', '::ffff:10.0.0.1', '::127.0.0.1',
    '64:ff9b::7f00:1', '64:ff9b::10.0.0.1', '2002:7f00:1::', '2002:c0a8:101::1', '2001::1', '100::1',
    'not an ip', '', '1.2.3', '1.2.3.4.5', '256.1.1.1', '1::2::3', '::ffff:999.0.0.1',
  ])('refuses %s', (ip) => {
    expect(isPublicAddress(ip)).toBe(false);
  });

  it.each([
    '1.1.1.1', '8.8.8.8', '93.184.215.14', '172.15.255.255', '172.32.0.1', '100.63.255.255', '100.128.0.1', '192.169.0.1',
    '2606:4700:4700::1111', '2a00:1450:4001:80b::200e', '::ffff:8.8.8.8', '64:ff9b::808:808', '2002:808:808::1',
  ])('allows %s', (ip) => {
    expect(isPublicAddress(ip)).toBe(true);
  });
});
